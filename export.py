HANDOVER_DISCLAIMER = (
    "This handover document is for orientation and preparation only. "
    "It is not a diagnosis or treatment recommendation. "
    "A qualified healthcare professional must review the original images and context."
)


def build_handover_markdown_report(
    snapshots: List["PhotoSnapshot"],
    role: str = "patient",
    user_id: str = "",
) -> str:
    """Build a Markdown handover report from a list of snapshots.

    Args:
        snapshots: Snapshots ordered from oldest to newest.
        role: Intended audience (patient, clinician, researcher).
        user_id: Optional user/session identifier.

    Returns:
        Markdown content as a string.
    """
    lines = [
        f"# {config.APP_NAME} - Handover Report",
        "",
        f"**Date:** {_now()}",
        f"**Audience:** {role.capitalize()}",
    ]
    if user_id:
        lines.append(f"**Patient/Session ID:** {user_id}")
    lines.extend(["", "## Timeline", ""])

    for idx, snapshot in enumerate(snapshots, start=1):
        lines.append(f"### Entry {idx} — {snapshot.created_at.strftime('%Y-%m-%d %H:%M UTC')}")
        if snapshot.body_site:
            lines.append(f"**Body site:** {snapshot.body_site}")
        if snapshot.encrypted_image:
            image = PILImage.open(io.BytesIO(snapshot.encrypted_image))
            lines.append(f"![Snapshot {idx}]({_image_to_data_uri(image)})")
            lines.append("")
        if snapshot.anamnesis:
            lines.extend(["**Anamnesis:**", "", snapshot.anamnesis, ""])
        if snapshot.analysis_summary:
            lines.extend(["**Summary:**", "", snapshot.analysis_summary, ""])
        lines.append("")

    lines.extend(
        [
            "---",
            "",
            f"*{HANDOVER_DISCLAIMER}*",
            "",
            f"Generated by [{config.COMPANY}]({config.COMPANY_URL})",
        ]
    )
    return "\n".join(lines)


def build_handover_pdf_report(
    snapshots: List["PhotoSnapshot"],
    role: str = "patient",
    user_id: str = "",
) -> bytes:
    """Build a PDF handover report from a list of snapshots."""
    if not PDF_EXPORT_AVAILABLE:
        raise RuntimeError("PDF export is unavailable because fpdf2 is not installed.")

    class _HandoverPDF(FPDF):
        def header(self) -> None:
            self.set_font("helvetica", "B", 12)
            self.cell(
                0,
                10,
                f"{config.APP_NAME} - Handover Report",
                new_x=XPos.LMARGIN,
                new_y=YPos.NEXT,
                align="L",
            )
            self.ln(2)

