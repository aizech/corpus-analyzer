    pdf.add_page()
    pdf.set_auto_page_break(auto=True, margin=20)
    pdf.set_font("helvetica", "", 10)

    pdf.cell(0, 6, f"Date: {_now()}", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.cell(0, 6, f"Audience: {role.capitalize()}", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    if user_id:
        pdf.cell(0, 6, f"Patient/Session ID: {user_id}", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.ln(4)

    pdf.set_font("helvetica", "B", 11)
    pdf.cell(0, 8, "Timeline", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
